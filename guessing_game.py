# Описание: Простая консольная игра. Программа загадывает 
# число, а пользователь пытается его угадать, получая подсказки.
# ==========================================

# Загаданное число (жестко задано в коде)
secret_number = 42

# Переменная для подсчета количества попыток
attempts = 0

print("--- Игра 'Угадай число' ---")
print("Компьютер загадал число. Попробуй угадать его!\n")

# Запускаем бесконечный цикл для игры
while True:
    # Запрашиваем число у пользователя и сразу считаем попытку
    user_num = int(input("Ваш вариант: "))
    attempts += 1
    
    # Если введенное число больше загаданного, подсказываем "Меньше!"
    if user_num > secret_number:
        print("Меньше!")
        
    # Если введенное число меньше загаданного, подсказываем "Больше!"
    elif user_num < secret_number:
        print("Больше!")
        
    # Если числа равны — это победа
    else:
        print(f"Победа! Вы угадали число за {attempts} попыток.")
        break # Прерываем цикл, так как игра окончена
